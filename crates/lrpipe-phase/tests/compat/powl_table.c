// Generates src/core/powl_table.rs: glibc's powl(10, -c/10.0L) for c in
// 0..1024, as WhatsHap's genotyping DP computes phred probabilities and
// recombination probabilities (x86-64, 80-bit long double). glibc's powl is
// not correctly rounded, so the values are taken from glibc itself.
//   gcc -O0 -o powl_table tests/compat/powl_table.c -lm && ./powl_table > src/core/powl_table.rs
#include <math.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
int main(void) {
    printf("//! glibc's `powl(10, -c/10.0L)` for c in 0..1024 as (sign and exponent,\n");
    printf("//! significand) of the 80-bit result. Generated by tests/compat/powl_table.c.\n\n");
    printf("pub const POW10_NEG_TENTHS: [(u16, u64); 1024] = [\n");
    for (int c = 0; c < 1024; c++) {
        long double v = powl(10, -(long double)c / 10.0L);
        uint64_t m;
        uint16_t e;
        memcpy(&m, &v, 8);
        memcpy(&e, (char *)&v + 8, 2);
        printf("    (0x%04x, 0x%016llx),\n", e, (unsigned long long)m);
    }
    printf("];\n");
    return 0;
}
